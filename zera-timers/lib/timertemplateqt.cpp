#include "timertemplateqt.h"
#include <QCoreApplication>

TimerTemplateQt::TimerTemplateQt(int expireTimeMs) :
    m_expireTimeMs(expireTimeMs)
{
}

bool TimerTemplateQt::silenceNextCriticalWhenCalledFromTest()
{
    static bool checked = false;

    bool current = checked;
    checked = true;

    return current;
}

void TimerTemplateQt::spawnCriticalWhenCalledFromTest()
{
    if (!silenceNextCriticalWhenCalledFromTest() && QCoreApplication::instance()->applicationName().startsWith("test_"))
        qCritical("TimerFactoryQtForTest::enableTest() called? / timer generated by TimerFactoryQt?");
}
